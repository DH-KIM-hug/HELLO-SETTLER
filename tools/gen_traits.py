def header(ws,row,cols,widths):
    for i,(h,w) in enumerate(zip(cols,widths),1):
        cell=ws.cell(row=row,column=i,value=h)
        cell.font=F(bold=True,color="FFFFFF"); cell.fill=HDR_FILL
