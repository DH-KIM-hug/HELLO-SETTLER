def recipe_ref(rid, col):
    return f"레시피!${col}${RROW[rid]}"


def write_node(rid, depth, demand_formula):
    """한 단계 행을 쓰고 상류 재귀. demand_formula: 이 행의 필요 산출/분."""
    global row
    r = row; row += 1
    bname = next(b[1] for b in B if b[0] == next(x for x in R if x[0] == rid)[1])
    put(wk, r, 1, ("    " * depth) + ("└ " if depth else "") + bname, bold=(depth == 0))
    put(wk, r, 2, rid)
    if depth == 0:
        put(wk, r, 3, demand_formula, inp=True, fmt="0.00")
    else:
        put(wk, r, 3, demand_formula, fmt="0.00")
    put(wk, r, 4, f"={recipe_ref(rid,'O')}")
    put(wk, r, 5, f"={recipe_ref(rid,'K')}")
    mult = (f"INDEX('기후 변형'!$H$2:$N${NCL},MATCH($B$3,'기후 변형'!$A$2:$A${NCL},0),"
            f"MATCH(E{r}&\" 배율\",'기후 변형'!$H$1:$N$1,0))")
    put(wk, r, 6, f"={recipe_ref(rid,'L')}*{mult}", fmt="0.00")
    put(wk, r, 7, f'=IF(F{r}=0,"불가",C{r}/F{r})', fmt="0.00")
    put(wk, r, 8, f'=IF(ISNUMBER(G{r}),ROUNDUP(G{r},0),"불가")')
    put(wk, r, 10, f"=IF(ISNUMBER(G{r}),G{r}*{recipe_ref(rid,'M')},0)", fmt="0.00")
    put(wk, r, 11, f"=IF(ISNUMBER(G{r}),G{r}*{recipe_ref(rid,'N')},0)", fmt="0.00")
    rec = next(x for x in R if x[0] == rid)
    for inp_good, col in ((rec[2], "J"), (rec[4], "K")):
        if inp_good and inp_good in PRODUCER:
            write_node(PRODUCER[inp_good], depth + 1, f"={col}{r}")
    return r


